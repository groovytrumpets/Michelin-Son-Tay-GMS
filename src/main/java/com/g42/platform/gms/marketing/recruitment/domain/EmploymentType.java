package com.g42.platform.gms.marketing.recruitment.domain;

/** Hình thức làm việc của một vị trí. Nhãn tiếng Việt do FE hiển thị. */
public enum EmploymentType {
    /** Toàn thời gian. */
    FULL_TIME,
    /** Bán thời gian / theo ca. */
    PART_TIME,
    /** Thực tập sinh, học việc. */
    INTERNSHIP,
    /** Thời vụ, cao điểm lễ tết. */
    SEASONAL,
    /** Cộng tác / khoán việc. */
    CONTRACT
}
